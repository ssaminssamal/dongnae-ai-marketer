from pathlib import Path

from video_merge import merge_video_bytes


# =========================================================
# outputs 폴더
# =========================================================

output_dir = Path("outputs")

output_dir.mkdir(
    parents=True,
    exist_ok=True,
)


# =========================================================
# 기존 Runway 개별 영상 찾기
# =========================================================

video_paths = sorted(
    output_dir.glob("ad_*.mp4"),
    key=lambda p: p.stat().st_mtime,
)

if not video_paths:
    raise RuntimeError(
        "outputs 폴더에 ad_*.mp4 영상이 없습니다."
    )


# =========================================================
# 영상 목록 출력
# =========================================================

print()
print("========== 영상 목록 ==========")
print()

for i, path in enumerate(
    video_paths,
    start=1,
):
    print(
        f"{i}. {path.name}"
    )


# =========================================================
# 사용할 영상 선택
# =========================================================

print()

choice = input(
    "사용할 영상 번호를 순서대로 입력하세요 "
    "(예: 1,3 또는 2,4): "
)

try:

    selected_numbers = [
        int(x.strip())
        for x in choice.split(",")
    ]

except ValueError:

    raise ValueError(
        "영상 번호를 1,2 형식으로 입력해주세요."
    )


# =========================================================
# 선택한 영상 검증
# =========================================================

selected_paths = []

for number in selected_numbers:

    if (
        number < 1
        or number > len(video_paths)
    ):

        raise ValueError(
            f"잘못된 영상 번호입니다: {number}"
        )

    selected_paths.append(
        video_paths[number - 1]
    )


# =========================================================
# 선택된 영상 출력
# =========================================================

print()
print("========== 선택된 영상 ==========")
print()

for i, path in enumerate(
    selected_paths,
    start=1,
):

    print(
        f"장면 {i}: {path.name}"
    )


# =========================================================
# 영상 파일 → bytes
# =========================================================

scene_videos = [
    path.read_bytes()
    for path in selected_paths
]


# =========================================================
# 마지막 장면 자막
# =========================================================

final_captions = [
    "바삭함이 다르다!",
    "갓 튀겨낸 따끈한 치킨",
    "오늘은 치킨 먹는 날",
]


# =========================================================
# TTS 내레이션
# =========================================================

narration_text = (
    "한 입 먹었는데, 한 조각이 사라졌습니다. "
    "갓 튀겨낸 바삭한 치킨. "
    "오늘은 맛있는 치킨과 함께하세요."
)


# =========================================================
# 기존 테스트 영상 제거
# =========================================================

test_final_path = (
    output_dir
    / "TTS_TEST_FINAL.mp4"
)

if test_final_path.exists():

    try:

        test_final_path.unlink()

    except PermissionError:

        raise RuntimeError(
            "TTS_TEST_FINAL.mp4가 현재 재생 중입니다. "
            "영상 플레이어를 완전히 닫고 다시 실행해주세요."
        )


# =========================================================
# 영상 + 자막 + TTS 합치기
# =========================================================

print()
print(
    "영상 + 자막 + TTS 합치는 중..."
)

merged_bytes, merged_path = (
    merge_video_bytes(
        scene_videos,
        final_captions=final_captions,
        narration_text=narration_text,
    )
)


# =========================================================
# 생성된 최종 파일
# =========================================================

generated_path = Path(
    merged_path
)


# =========================================================
# 최종 파일 이름을 하나로 고정
# =========================================================

generated_path.replace(
    test_final_path
)


# =========================================================
# 최종 결과 확인
# =========================================================

if not test_final_path.exists():

    raise RuntimeError(
        "최종 영상 파일 생성에 실패했습니다."
    )


# =========================================================
# 완료
# =========================================================

print()
print("================================")
print("완료!")
print()

print(
    "영상 + 자막 + TTS가 합쳐진 최종 파일:"
)

print(
    test_final_path
)

print()
print(
    "별도의 MP3 파일은 생성하지 않습니다."
)

print("================================")